CREATE TABLE bulletin_boards (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    building_id BIGINT NOT NULL UNIQUE,
    FOREIGN KEY (building_id) REFERENCES buildings(id)
);

CREATE TABLE advertisements (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    bulletin_board_id BIGINT NOT NULL,
    tenant_id BIGINT NOT NULL,
    description TEXT NOT NULL,
    is_offering BOOLEAN NOT NULL,
    start_date TIMESTAMP NOT NULL,
    end_date TIMESTAMP NOT NULL,
    category VARCHAR(100) NOT NULL,
    status VARCHAR(50) NOT NULL,
    FOREIGN KEY (bulletin_board_id) REFERENCES bulletin_boards(id),
    FOREIGN KEY (tenant_id) REFERENCES users(id)
);

CREATE TABLE advertisement_slots (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    advertisement_id BIGINT NOT NULL,
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    FOREIGN KEY (advertisement_id) REFERENCES advertisements(id)
);

CREATE TABLE slot_reservations (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    slot_id BIGINT NOT NULL,
    requester_ad_id BIGINT NOT NULL,
    tenant_id BIGINT NOT NULL,
    FOREIGN KEY (slot_id) REFERENCES advertisement_slots(id),
    FOREIGN KEY (requester_ad_id) REFERENCES advertisements(id),
    FOREIGN KEY (tenant_id) REFERENCES users(id)
);


