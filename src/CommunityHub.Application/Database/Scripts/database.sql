-- ============================================================
--  Korisnici
-- ============================================================
CREATE TABLE users (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    surname VARCHAR(100) NOT NULL,
    birthday DATE NOT NULL,
    role VARCHAR(50) NOT NULL,
    address VARCHAR(300),
    CONSTRAINT chk_user_role
        CHECK (role IN ('BuildingManager', 'Tenant', 'DistrictCoordinator', 'Citizen'))
);

-- Legacy iz starter projekta (primer) — biće uklonjeno kasnije
CREATE TABLE posts (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    user_id BIGINT NOT NULL,
    FOREIGN KEY (user_id) REFERENCES users(id)
);


-- ============================================================
--  Lokacije i kvartovi (Koordinator kvarta)
-- ============================================================
CREATE TABLE locations (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    city VARCHAR(100) NOT NULL,
    country VARCHAR(100) NOT NULL
);

CREATE TABLE districts (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    location_id BIGINT NOT NULL,
    budget DECIMAL(18, 2) NOT NULL DEFAULT 0,
    coordinator_id BIGINT NOT NULL,
    FOREIGN KEY (location_id) REFERENCES locations(id),
    FOREIGN KEY (coordinator_id) REFERENCES users(id)
);

CREATE TABLE district_streets (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    district_id BIGINT NOT NULL,
    street_name VARCHAR(200) NOT NULL,
    start_number INT NOT NULL,
    end_number INT NOT NULL,
    FOREIGN KEY (district_id) REFERENCES districts(id)
);

-- Slike za kvart
CREATE TABLE images (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    url VARCHAR(500) NOT NULL,
    district_id BIGINT NOT NULL,
    FOREIGN KEY (district_id) REFERENCES districts(id)
);

-- Zahtevi za pristup kvartu
CREATE TABLE district_access_requests (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    district_id BIGINT NOT NULL,
    creation_date TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Pending',
    rejection_reason TEXT,
    FOREIGN KEY (user_id) REFERENCES users(id),
    FOREIGN KEY (district_id) REFERENCES districts(id)
);

-- Članstva u kvartu
CREATE TABLE district_memberships (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    district_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    join_date TIMESTAMP NOT NULL,
    trust_level VARCHAR(30) NOT NULL DEFAULT 'Nov',
    CONSTRAINT chk_trust_level
        CHECK (trust_level IN ('Nov', 'Neaktivan', 'Aktivan', 'Istaknuti', 'OdPoverenja')),
    FOREIGN KEY (district_id) REFERENCES districts(id),
    FOREIGN KEY (user_id) REFERENCES users(id)
);

-- Sastanci koordinatora kvarta
CREATE TABLE district_meetings (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    district_id BIGINT NOT NULL,
    meeting_type VARCHAR(20) NOT NULL,
    meeting_time TIME NOT NULL,
    date_range_start DATE NOT NULL,
    date_range_end DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'UPripremi',
    scheduled_date DATE,
    CONSTRAINT chk_meeting_type CHECK (meeting_type IN ('Dobrodoslica', 'Motivacija')),
    CONSTRAINT chk_meeting_status CHECK (status IN ('UPripremi', 'Zakazan', 'Otkazan')),
    FOREIGN KEY (district_id) REFERENCES districts(id)
);

-- Glasovi građana za termine sastanaka
CREATE TABLE district_meeting_votes (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    meeting_id BIGINT NOT NULL,
    citizen_id BIGINT NOT NULL,
    preferred_date DATE NOT NULL,
    CONSTRAINT uq_meeting_citizen_vote UNIQUE (meeting_id, citizen_id),
    FOREIGN KEY (meeting_id) REFERENCES district_meetings(id),
    FOREIGN KEY (citizen_id) REFERENCES users(id)
);

-- Dogadjaji gradjana u kvartu
CREATE TABLE district_events (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    district_id BIGINT NOT NULL,
    organizer_id BIGINT NOT NULL,
    name VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    event_date DATE NOT NULL,
    start_time TIME NOT NULL,
    duration_minutes INT NOT NULL,
    min_volunteers INT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'UPripremi',
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT chk_district_event_status CHECK (status IN ('UPripremi', 'Zakazan', 'Otkazan', 'Zavrsen')),
    CONSTRAINT chk_district_event_duration CHECK (duration_minutes > 0),
    CONSTRAINT chk_district_event_min_volunteers CHECK (min_volunteers > 0),
    FOREIGN KEY (district_id) REFERENCES districts(id),
    FOREIGN KEY (organizer_id) REFERENCES users(id)
);

CREATE TABLE district_event_required_items (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    event_id BIGINT NOT NULL,
    item_name VARCHAR(200) NOT NULL,
    assigned_volunteer_id BIGINT,
    FOREIGN KEY (event_id) REFERENCES district_events(id) ON DELETE CASCADE,
    FOREIGN KEY (assigned_volunteer_id) REFERENCES users(id)
);

CREATE TABLE district_event_applications (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    event_id BIGINT NOT NULL,
    citizen_id BIGINT NOT NULL,
    applied_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_district_event_citizen UNIQUE (event_id, citizen_id),
    FOREIGN KEY (event_id) REFERENCES district_events(id) ON DELETE CASCADE,
    FOREIGN KEY (citizen_id) REFERENCES users(id)
);

CREATE TABLE district_event_application_items (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    application_id BIGINT NOT NULL,
    required_item_id BIGINT NOT NULL,
    CONSTRAINT uq_district_event_item_once UNIQUE (required_item_id),
    FOREIGN KEY (application_id) REFERENCES district_event_applications(id) ON DELETE CASCADE,
    FOREIGN KEY (required_item_id) REFERENCES district_event_required_items(id) ON DELETE CASCADE
);

CREATE TABLE district_event_volunteer_attendances (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    event_id BIGINT NOT NULL,
    volunteer_id BIGINT NOT NULL,
    attended BOOLEAN NOT NULL,
    marked_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_district_event_volunteer_attendance UNIQUE (event_id, volunteer_id),
    FOREIGN KEY (event_id) REFERENCES district_events(id) ON DELETE CASCADE,
    FOREIGN KEY (volunteer_id) REFERENCES users(id)
);


