BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'chk_trust_level'
    ) THEN
        ALTER TABLE district_memberships
            ADD CONSTRAINT chk_trust_level
            CHECK (trust_level IN ('Nov', 'Neaktivan', 'Aktivan', 'Istaknuti', 'OdPoverenja'));
    END IF;
END $$;

