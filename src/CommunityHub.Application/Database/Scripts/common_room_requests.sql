CREATE TABLE common_room_requests (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    tenant_id BIGINT NOT NULL,
    common_room_id BIGINT NOT NULL,
    requested_start_date TIMESTAMP NOT NULL,
    requested_end_date TIMESTAMP NOT NULL,
    proposed_start_date TIMESTAMP,
    proposed_end_date TIMESTAMP,
    approved_date TIMESTAMP,
    status VARCHAR(50) NOT NULL,
    FOREIGN KEY (tenant_id) REFERENCES users(id),
    FOREIGN KEY (common_room_id) REFERENCES common_rooms(id)
);
